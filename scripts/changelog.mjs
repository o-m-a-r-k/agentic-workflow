#!/usr/bin/env node
// Writes CHANGELOG.md from the release notes (docs/releases/v*.md, newest first) and the improvement history
// (I-*.md: each failure, the release that fixed it and its scenario test).
//   node scripts/changelog.mjs
//
// 0.8.0 (L13) took the improvement history out of the shipped tree; it stays in git. The entries are read from
// `improvements/` while a checkout still holds it, else from git: the tree just before the commit that removed it.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = 'improvements';
const ver = (s) => s.split('.').map(Number);
const newer = (a, b) => {
  const [x, y] = [ver(a), ver(b)];
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return y[i] - x[i];
  return 0;
};
const git = (args) => {
  const r = spawnSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  if (r.status !== 0) throw new Error(`git ${args.join(' ')} failed: ${(r.stderr || r.stdout || '').trim()}`);
  return r.stdout;
};

// [{ name, text }] of every I-<n>.md, from the checkout or from git history.
function improvementFiles() {
  const dir = path.join(ROOT, DIR);
  if (fs.existsSync(dir)) return fs.readdirSync(dir).filter((f) => /^I-\d+\.md$/.test(f)).map((name) => ({ name, text: fs.readFileSync(path.join(dir, name), 'utf8') }));
  // HEAD itself when its removal is not committed yet, else the parent of the last commit that touched it (its removal).
  const inHead = spawnSync('git', ['cat-file', '-e', `HEAD:${DIR}`], { cwd: ROOT }).status === 0;
  const removedBy = inHead ? null : git(['rev-list', '-1', 'HEAD', '--', `${DIR}/`]).trim();
  if (!inHead && !removedBy) throw new Error(`no ${DIR}/ in this checkout and none in its git history, so the improvement history cannot be read (a shallow clone or an export holds no history): run it in a full clone`);
  const ref = inHead ? 'HEAD' : `${removedBy}^`;
  const names = git(['ls-tree', '--name-only', `${ref}:${DIR}`]).split('\n').filter((f) => /^I-\d+\.md$/.test(f));
  return names.map((name) => ({ name, text: git(['show', `${ref}:${DIR}/${name}`]) }));
}

const notes = fs.readdirSync(path.join(ROOT, 'docs', 'releases')).filter((f) => /^v\d+\.\d+\.\d+\.md$/.test(f)).map((f) => f.slice(1, -3)).sort(newer);
const items = improvementFiles().map(({ name, text }) => ({
  id: name.slice(0, -3), n: Number(name.slice(2, -3)), title: /^# I-\d+: (.+)$/m.exec(text)?.[1] ?? '', fixed: /\*\*Fixed in:\*\* (.+)$/m.exec(text)?.[1] ?? '', test: /\*\*Test:\*\* (.+)$/m.exec(text)?.[1] ?? '',
})).sort((a, b) => b.n - a.n);

const out = ['# Changelog', '', 'Release notes, newest first, then every fix that came from a failure in the workflow itself. Generated by `node scripts/changelog.mjs` from `docs/releases/` and `improvements/`.', ''];
for (const v of notes) out.push(fs.readFileSync(path.join(ROOT, 'docs', 'releases', `v${v}.md`), 'utf8').trim(), '');
out.push('## Improvement history', '', '| Item | Failure fixed | Fixed in | Scenario test |', '| --- | --- | --- | --- |');
// Plain ids, no links: the files left the shipped tree (their text is in git).
for (const i of items) out.push(`| ${i.id} | ${i.title} | ${i.fixed} | ${i.test.split(' (')[0]} |`);
fs.writeFileSync(path.join(ROOT, 'CHANGELOG.md'), `${out.join('\n')}\n`);
console.log(`CHANGELOG.md: ${notes.length} release(s), ${items.length} improvement(s)`);
