// The two file formats a harness reads custom agents from, and the markers that say `wf sync` wrote them.

export const GENERATED_MD = '<!-- generated by `wf sync` from agentic-workflow; edit .workflow/ instead -->';
export const GENERATED_TOML = '# generated by `wf sync` from agentic-workflow; edit .workflow/ instead';
// A file one of our formats wrote: `wf sync` removes such a file when it no longer produces it.
export const isGeneratedRoleFile = (text) => text.includes(GENERATED_MD) || text.includes(GENERATED_TOML);

// TOML basic strings: escape backslash, quote and control characters.
const tomlEscape = (s, keepNewlines) => s.replace(/[\\"\u0000-\u001f\u007f]/g, (ch) => (ch === '\\' ? '\\\\' : ch === '"' ? '\\"' : keepNewlines && ch === '\n' ? '\n' : ch === '\n' ? '\\n' : ch === '\t' ? '\\t' : `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`));
export const tomlString = (s) => `"${tomlEscape(String(s), false)}"`;
const tomlMultiline = (s) => `"""\n${tomlEscape(String(s), true)}"""`;

// A markdown agent file: frontmatter (`tools` when the harness takes a tool list), the marker, the instructions.
export function markdownRole({ name, description, model, effort, tools, body }) {
  // JSON strings are valid YAML scalars, so a `use` text with colons cannot break the frontmatter.
  const front = ['---', `name: ${name}`, `description: ${JSON.stringify(description)}`, model ? `model: ${model}` : null, effort ? `effort: ${effort}` : null, tools ? `tools: ${tools.join(', ')}` : null, '---'].filter(Boolean).join('\n');
  return `${front}\n${GENERATED_MD}\n${body.trimEnd()}\n`;
}

// A TOML agent file with its instructions as a multi-line string.
export function tomlRole({ name, description, model, effort, body }) {
  const lines = [GENERATED_TOML, `name = ${tomlString(name)}`, `description = ${tomlString(description)}`, model ? `model = ${tomlString(model)}` : null, effort ? `model_reasoning_effort = ${tomlString(effort)}` : null, `developer_instructions = ${tomlMultiline(body)}`];
  return `${lines.filter(Boolean).join('\n')}\n`;
}
